\ stars.fs — треугольник из звёздочек
\
\ Выводит:
\   *
\   **
\   ***
\   ****
\   *****
\
\ Вложенные циклы DO...LOOP и EMIT (печать символа по коду, 42 = '*').
\
\ Запуск:  forth usr/examples/stars.fs

: stars ( n -- )
  1+ 1 do              \ строка I = 1..n
    i 0 do             \ вывести I звёздочек
      42 emit          \ 42 — код символа '*'
    loop
    cr
  loop
;

5 stars
