\ greet.fs — спрашивает имя и отвечает Hello, <имя>!
\
\ Строка читается словом accept — это строчный режим ядра (тот же, что
\ у шелла), поэтому здесь бесплатно работают: эхо, Backspace, стрелки
\ ←/→, Home/End/Delete и история ↑/↓. Enter в строку не попадает.
\
\ Запуск:  forth usr/examples/greet.fs

: greet
  ." Как вас зовут? "
  here 32 accept          \ ( n ) — имя с полным редактированием строки
  ." Hello, "
  here swap type          \ напечатать введённое имя ( addr len -- )
  ." !" cr
;

greet
