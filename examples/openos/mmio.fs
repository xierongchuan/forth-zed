\ mmio.fs — прямой доступ к памяти и выполнение машинного кода
\
\ PMP ядра разрешает U-режиму доступ ко ВСЕЙ физической памяти (R/W/X),
\ поэтому Forth может читать/писать регистры MMIO словами peek/poke и
\ выполнять hex-код словами hex, + call.
\
\ Важно: peek/poke/call работают с АБСОЛЮТНЫМИ адресами, а данные Forth
\ (here, @, !, hex,) — со СМЕЩЕНИЯМИ. Мост между ними — слово data-base.
\
\ Запуск:  forth usr/examples/mmio.fs

\ 1) Читаем «магию» virtio-устройства по абсолютному адресу 0x10001000.
\    Должно получиться 1953655158 = 0x74726976 (символы "virt").
$10001000 4 peek .
."   (должно быть 1953655158 = 0x74726976 = 'virt')" cr

\ 2) Выполняем машинный код из буфера: addi a0,a0,1 ; ret
\    0x00150513 = addi a0, a0, 1     0x00008067 = ret
\    call ( arg addr -- ret ): передаёт arg в a0 и возвращает a0 после ret.
41                          \ аргумент (a0)
s" 1305150067800000" hex,   \ ( arg off n ) — байты кода записаны в here
drop                        \ ( arg off )
data-base +                 \ ( arg abs-addr )
call                        \ ( ret )
." 41 + 1 = " . cr

\ 3) poke/peek в собственный буфер данных (безопасная запись в RAM):
\    пишем 123 по адресу data-base+100 и читаем обратно.
data-base 100 +             \ ( addr )
dup                         \ ( addr addr )
123 swap 4 poke             \ ( addr ) — записали 123
4 peek                      \ ( val )
." poke/peek: " . cr
